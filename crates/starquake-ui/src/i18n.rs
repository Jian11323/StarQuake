//! 界面语言：简体中文 / 繁体中文 / 日语 / 英语。
//! 以简体中文原文为查找键；缺译时回退简体。

use std::cell::Cell;
use std::collections::HashMap;
use std::sync::OnceLock;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Lang {
    ZhCn,
    ZhTw,
    Ja,
    En,
}

impl Lang {
    pub fn parse(s: &str) -> Self {
        match starquake_config::normalize_ui_language(s).as_str() {
            "zh-TW" => Self::ZhTw,
            "ja" => Self::Ja,
            "en" => Self::En,
            _ => Self::ZhCn,
        }
    }

    pub fn as_config(self) -> &'static str {
        match self {
            Self::ZhCn => "zh-CN",
            Self::ZhTw => "zh-TW",
            Self::Ja => "ja",
            Self::En => "en",
        }
    }

    /// 语言自身名称（不随界面语言翻译）。
    pub fn native_name(self) -> &'static str {
        match self {
            Self::ZhCn => "简体中文",
            Self::ZhTw => "繁體中文",
            Self::Ja => "日本語",
            Self::En => "English",
        }
    }

    pub const ALL: [Self; 4] = [Self::ZhCn, Self::ZhTw, Self::Ja, Self::En];
}

thread_local! {
    static CURRENT: Cell<Lang> = const { Cell::new(Lang::ZhCn) };
}

pub fn set_lang(lang: Lang) {
    CURRENT.set(lang);
}

pub fn lang() -> Lang {
    CURRENT.get()
}

pub fn set_lang_from_config(s: &str) {
    set_lang(Lang::parse(s));
}

/// 将简体中文 UI 文案译为当前语言。
pub fn t(zh_cn: &str) -> &str {
    match lang() {
        Lang::ZhCn => zh_cn,
        other => table()
            .get(&(other, zh_cn))
            .copied()
            .unwrap_or(zh_cn),
    }
}

